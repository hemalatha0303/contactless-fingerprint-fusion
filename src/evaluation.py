import os
import numpy as np
import pandas as pd
import matplotlib

# Headless cloud containers (Streamlit Cloud, HF Spaces, Render, etc.)
# have no display. matplotlib usually falls back to Agg on its own,
# but that autodetection depends on environment variables that not
# every platform sets consistently -- pin it explicitly so plotting
# never fails at deploy time for a reason that never shows up
# locally.
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from sklearn.metrics import (
    roc_curve,
    auc,
    confusion_matrix
)


# -------------------------------
# Load Results
# -------------------------------

def load_results(csv_path="outputs/results.csv"):
    """
    Load similarity scores generated by main.py
    """

    if not os.path.exists(csv_path):
        raise FileNotFoundError(
            f"{csv_path} not found."
        )

    return pd.read_csv(csv_path)


# -------------------------------
# EER
# -------------------------------

def compute_eer(labels, scores):

    fpr, tpr, thresholds = roc_curve(
        labels,
        scores
    )

    fnr = 1 - tpr

    idx = np.argmin(
        np.abs(fpr - fnr)
    )

    eer = (fpr[idx] + fnr[idx]) / 2

    threshold = thresholds[idx]

    return eer, threshold


# -------------------------------
# TAR at a fixed FAR operating point
# -------------------------------

def tar_at_far(labels, scores, target_far):
    """
    True Acceptance Rate at the point on the ROC curve closest to
    (but not exceeding) the requested False Acceptance Rate.
    """

    fpr, tpr, _ = roc_curve(labels, scores)

    valid = fpr <= target_far

    if not np.any(valid):
        return float(tpr[0])

    return float(tpr[valid].max())


# -------------------------------
# FAR FRR TAR at the EER threshold
# -------------------------------

def compute_metrics(labels, scores, threshold):

    predictions = (
        scores >= threshold
    ).astype(int)

    cm = confusion_matrix(
        labels,
        predictions
    )

    TN, FP, FN, TP = cm.ravel()

    FAR = FP / (FP + TN)

    FRR = FN / (FN + TP)

    TAR = TP / (TP + FN)

    return FAR, FRR, TAR, cm


# -------------------------------
# Multi-system comparison
# -------------------------------

# label -> results.csv column
SYSTEMS = {
    "Baseline: Minutiae only": "minutiae",
    "Secondary: Gabor Texture only": "texture",
    "Fusion: Weighted (tuned)": "fusion_weighted",
    "Fusion: Classifier (CV)": "fusion_ml",
}


def plot_roc_comparison(df, out_path="outputs/roc_curve.png"):

    plt.figure(figsize=(8, 7))

    summary = []

    for name, col in SYSTEMS.items():

        fpr, tpr, _ = roc_curve(df["label"], df[col])
        roc_auc = auc(fpr, tpr)

        style = "--" if "Baseline" in name or "Secondary" in name else "-"
        width = 1.5 if style == "--" else 2.5

        plt.plot(
            fpr, tpr, style, linewidth=width,
            label=f"{name} (AUC = {roc_auc:.4f})"
        )

        eer, eer_thresh = compute_eer(df["label"], df[col])

        summary.append({
            "system": name,
            "auc": roc_auc,
            "eer": eer,
            "tar_at_far_0.01": tar_at_far(df["label"], df[col], 0.01),
            "tar_at_far_0.001": tar_at_far(df["label"], df[col], 0.001),
        })

    plt.plot([0, 1], [0, 1], ":", color="gray", linewidth=1)

    plt.xlabel("False Acceptance Rate (FAR)")
    plt.ylabel("True Acceptance Rate (TAR)")
    plt.title("ROC Curve Comparison: Baseline vs. Fused Systems")
    plt.legend(loc="lower right", fontsize=9)
    plt.grid(True, linestyle=":", alpha=0.6)
    plt.tight_layout()

    os.makedirs("outputs", exist_ok=True)
    plt.savefig(out_path, dpi=300, bbox_inches="tight")
    plt.close()

    return pd.DataFrame(summary)


# -------------------------------
# Evaluation
# -------------------------------

def evaluate():

    df = load_results()

    summary_df = plot_roc_comparison(df)

    print("\n========== Comparative Evaluation ==========\n")
    print(summary_df.to_string(index=False, float_format=lambda v: f"{v:.4f}"))

    best_row = summary_df.loc[summary_df["auc"].idxmax()]

    print(f"\nBest system: {best_row['system']} (AUC = {best_row['auc']:.4f})")

    # detailed confusion-matrix breakdown for the best (final) fusion system
    labels = df["label"]
    scores = df["fusion"]

    eer, threshold = compute_eer(labels, scores)
    FAR, FRR, TAR, cm = compute_metrics(labels, scores, threshold)

    print("\n---- Final Fusion System (Weighted, tuned) @ EER threshold ----")
    print(f"EER       : {eer:.4f}")
    print(f"Threshold : {threshold:.4f}")
    print(f"FAR       : {FAR:.4f}")
    print(f"FRR       : {FRR:.4f}")
    print(f"TAR       : {TAR:.4f}")
    print("\nConfusion Matrix")
    print(cm)

    summary_df.to_csv("outputs/evaluation_summary.csv", index=False)
    print("\nROC comparison saved to outputs/roc_curve.png")
    print("Summary table saved to outputs/evaluation_summary.csv")


if __name__ == "__main__":
    evaluate()
